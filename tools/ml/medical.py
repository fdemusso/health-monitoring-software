"""The medical family of the stage-B diagnoser, trained on the crew dataset (``train_diagnoser.py --families medical``) and tuned and
read on the validation seeds (``sweep_diagnoser.py --medical``).

Data. Positives: every row of an M run (seeds ``--train-seeds``) from the moment the effect is visible. Negatives: the rows before the
start of the M runs, the N1 runs (nominal, with programme jitter: they hold the exercise) and the older catalog runs of
``output/ml/feat`` (a machine fault must not look like an illness; their medical events are positives). ``--stride`` thins only the
nominal rows: the positives are scarce (a few hundred rows for an arrhythmia).

Twins. The visible time of a fault comes from its TWIN, the nominal run with the same seed, the same length (or longer) and NO
programme jitter: until the fault acts the two are identical. The twin is looked up by (seed, days, no jitter, no fault), never by
seed alone (an N1 run of the same seed has a different programme from the first second), and before it is used the two runs are
compared on every row before the start of the fault: any difference stops the training (the determinism would not hold).

Thresholds. Per class, the lowest ``min_proba`` with at most ``--fa-target`` false alarms per day on the nominal days of the
validation seeds (N1 val and the stretch of every M val run before its event), counting the debounce (``confirm_s`` of
``classes.yaml``). A class with fewer than ``--min-rows`` positive rows in training is trained but NOT live: the card says so and
the detector ignores it (lesson d).
"""

from __future__ import annotations

import datetime
import json
import sys
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))

from crew_data import OUTPUT, CrewRun, default_dirs, find_runs, parse_seeds
from train_anomaly import provenance
from train_diagnoser import feature_columns, labelled, visible_since

AFTER_END_S = 1800.0
THRESHOLDS = (0.3, 0.4, 0.5, 0.6, 0.7, 0.8, 0.85, 0.9, 0.95, 0.98, 0.99)
MEDICAL = "medical"


class TwinMismatch(SystemExit):
    """The run and its twin differ before the fault starts: the determinism does not hold, stop."""


# ------------------------------------------------------------------ runs and twins
def load_all(dirs: list[Path] | None = None) -> list[CrewRun]:
    """The crew runs of every ``crew*`` folder plus the older catalog runs (``output/ml/feat``), by name, read-only."""
    runs = find_runs(dirs or default_dirs(), prefix="", need="features.parquet")  # prefix "": the twins are called nominal_s*
    catalog = OUTPUT / "feat"
    if catalog.is_dir():
        seen = {r.name for r in runs}
        runs += [r for r in find_runs([catalog], prefix="", need="features.parquet") if r.name not in seen]
    return runs


def twin_index(runs: list[CrewRun]) -> dict[int, list[CrewRun]]:
    """seed -> the nominal runs without jitter (the programme of the demo), shortest first."""
    out: dict[int, list[CrewRun]] = {}
    for r in runs:
        if not r.faults and not r.jitter and r.group in ("", "T"):
            out.setdefault(r.seed, []).append(r)
    return {s: sorted(v, key=lambda r: r.days) for s, v in out.items()}


def find_twin(run: CrewRun, twins: dict[int, list[CrewRun]]) -> CrewRun | None:
    """The shortest nominal run, same seed and no jitter, that is at least as long as ``run``."""
    return next((t for t in twins.get(run.seed, []) if t.days >= run.days - 1e-9), None)


_checked: set[tuple[str, str]] = set()
identity_log: list[dict] = []  # every pair checked and the largest difference seen: goes into the model card
CATALOG_TOL = 1e-6  # the older catalog (output/ml/feat) was generated by an earlier code version: one float32 ulp in a cancelling variance is tolerated
CROSS_PLATFORM_REL = 2.4e-7  # two float32 ulps: Windows and macOS differ in the last bit of a few cells (cancelling variances, slopes)


def platform_of(run: CrewRun) -> str:
    """Where a run was generated, from the scenario path the generator wrote in ``meta.json``: ``posix`` (a Mac) or ``windows``."""
    return "posix" if str(run.job.get("scenario", "")).startswith("/") else "windows"


def check_identity(run: CrewRun, twin: CrewRun, catalog_tol: float = CATALOG_TOL, cross_rel: float = CROSS_PLATFORM_REL) -> None:
    """Features and crew features of ``run`` and ``twin`` must be IDENTICAL on every row before the fault starts: difference exactly 0
    when both were generated on the same platform (the determinism); at most ``cross_rel`` relative (two float32 ulps) when one was made
    on Windows and the other on a Mac; the older catalog pairs (no ``group``, folder ``feat``) with the absolute ``catalog_tol``. The
    rule used and the largest difference seen go to the model card."""
    key = (run.name, twin.name)
    if key in _checked or not run.faults:
        return
    old = "feat" in (run.path.parent.name, twin.path.parent.name)
    cross = platform_of(run) != platform_of(twin)
    rule = "catalog_abs" if old else "cross_platform_rel" if cross else "same_platform_exact"
    start = min(float(f["start_s"]) for f in run.faults.values())
    for name in ("features.parquet", "crew.parquet"):
        if not (run.path / name).exists() or not (twin.path / name).exists():
            continue
        a, b = pd.read_parquet(run.path / name), pd.read_parquet(twin.path / name)
        a, b = a[a["t_s"] < start], b[b["t_s"] < start]
        keys = ["t_s", "npc"] if "npc" in a.columns else ["t_s"]
        m = a.merge(b, on=keys, suffixes=("", "_twin"))
        if len(m) != len(a):
            raise TwinMismatch(f"twin {twin.name} lacks rows of {run.name} before the fault ({len(m)} of {len(a)}): stop")
        num = [c for c in a.columns if c not in keys and pd.api.types.is_float_dtype(a[c]) and not c.startswith("truth|")]
        max_abs = max_rel = 0.0
        ok = True
        for c in num:
            x, y = m[c].to_numpy(dtype=np.float64), m[c + "_twin"].to_numpy(dtype=np.float64)
            d = np.abs(x - y)
            if np.isnan(d).any() and not (np.isnan(x) == np.isnan(y)).all():
                ok = False  # a NaN on one side only
            d = np.nan_to_num(d)
            scale = np.maximum(np.maximum(np.abs(np.nan_to_num(x)), np.abs(np.nan_to_num(y))), 1e-30)
            max_abs = max(max_abs, float(d.max(initial=0.0)))
            max_rel = max(max_rel, float((d / scale).max(initial=0.0)))
            if rule == "same_platform_exact":
                ok &= not (d > 0).any()
            elif rule == "cross_platform_rel":
                ok &= bool((d <= cross_rel * scale + 1e-12).all())
            else:
                ok &= bool((d <= catalog_tol).all())
        identity_log.append({"run": run.name, "twin": twin.name, "file": name, "rule": rule, "max_abs_diff": max_abs, "max_rel_diff": max_rel})
        if not ok:
            raise TwinMismatch(f"{run.name} and its twin {twin.name} differ before the fault starts beyond the rule {rule} (max abs {max_abs:.3g}, "
                               f"max rel {max_rel:.3g}) in {name}: the determinism does not hold. Stop and report.")
    _checked.add(key)


FALLBACK_LABELS: set[str] = {"dehydration"}  # classes whose effect never reaches k sigmas against the twin: visible = start + ramp (+ 1 h), declared in the card


def fallback_visible(run: CrewRun) -> dict[str, float | None]:
    """Without a twin: the start + ``ramp_s`` (+ 1 h for the dehydration, which has no sudden onset). Declared in the model card."""
    out = {}
    for fid, f in run.faults.items():
        ramp = float(f.get("params", {}).get("ramp_s", 0.0))
        out[fid] = float(f["start_s"]) + ramp + (3600.0 if f["label"] == "dehydration" else 0.0)
    return out


def identity_summary() -> dict:
    """What the identity checks found, per rule: pairs, pairs with any difference, the largest absolute and relative differences."""
    out: dict = {"cross_platform_rel_tolerance": CROSS_PLATFORM_REL, "catalog_abs_tolerance": CATALOG_TOL}
    for rule in ("same_platform_exact", "cross_platform_rel", "catalog_abs"):
        rows = [d for d in identity_log if d["rule"] == rule]
        pairs = {(d["run"], d["twin"]) for d in rows}
        out[rule] = {"pairs": len(pairs), "pairs_with_a_difference": len({(d["run"], d["twin"]) for d in rows if d["max_abs_diff"] > 0}),
                     "max_abs_diff": max((d["max_abs_diff"] for d in rows), default=0.0), "max_rel_diff": max((d["max_rel_diff"] for d in rows), default=0.0)}
    return out


# ------------------------------------------------------------------ labelled rows
@dataclass
class Prepared:
    run: CrewRun
    df: pd.DataFrame  # features of the run (the columns of the model) and ``t_s``
    y: np.ndarray  # label of the family per row: ``nominal`` / a class / ``drop``
    visible: dict[str, float | None]
    how: str  # ``twin`` | ``start+ramp``


def prepare(run: CrewRun, twins, scale, cols, classes, k: float, allow_fallback: bool) -> Prepared | None:
    """Rows of one run with their labels for the medical family; None when the run has a fault but no twin (and no fallback allowed)."""
    df = run.features
    if not run.faults:
        vis, how = {}, "nominal"
    else:
        twin = find_twin(run, twins)
        if twin is not None:
            check_identity(run, twin)
            vis = visible_since({"df": df, "meta": run.meta}, {"df": twin.features}, scale, cols, k)
            how = "twin"
        elif allow_fallback:
            vis, how = fallback_visible(run), "start+ramp"
        else:
            return None
    for fid, f in run.faults.items():  # a slow class the twin cannot see (the dehydration peaks at 1.4-2.7 sigmas of the station scale)
        if f["label"] in FALLBACK_LABELS:
            vis[fid] = fallback_visible(run)[fid]
            how += f"+fallback({f['label']})"
    y = labelled({"df": df, "meta": run.meta}, vis, classes)[f"y_{MEDICAL}"].to_numpy()
    return Prepared(run, df, y, vis, how)


def keep_rows(y: np.ndarray, stride: int) -> np.ndarray:
    """Every positive row, every ``stride``-th nominal one, no ``drop``."""
    idx = np.arange(len(y))
    return (y != "drop") & ((y != "nominal") | (idx % stride == 0))


def is_training_run(r: CrewRun, seeds: set[int]) -> bool:
    single = len(r.faults) <= 1 and "+" not in r.name and "extra_faults" not in r.job
    if r.seed not in seeds or not single:
        return False
    catalog = r.group == "" and r.path.parent.name == "feat"
    return r.group == "N1" or r.group.startswith("M") or catalog  # N1, the M events, the older catalog; not E, C, R1 nor the twins


# ------------------------------------------------------------------ validation
@dataclass
class ValRun:
    name: str
    group: str
    event: str | None
    t: np.ndarray
    proba: np.ndarray  # (rows, classes of the family)
    y: np.ndarray
    start_s: float | None
    end_s: float | None
    visible_s: float | None
    npc: str | None
    x: np.ndarray | None = None  # the feature rows (only when asked: the subject of an alarm is read from them)
    how: str = "nominal"  # where visible_s comes from


def predict_val(clf, runs: list[CrewRun], twins, scale, cols, classes, k, allow_fallback, keep_x: bool = False) -> list[ValRun]:
    out = []
    for r in runs:
        prep = prepare(r, twins, scale, cols, classes, k, allow_fallback)
        if prep is None:
            print(f"no twin for {r.name}: skipped", flush=True)
            continue
        f = next(iter(r.faults.values()), None)
        start = float(f["start_s"]) if f else None
        end = start + float(f.get("duration_s") or 0.0) if f else None
        vis = next(iter(prep.visible.values()), None) if prep.visible else None
        out.append(ValRun(r.name, r.group, f["label"] if f else None, prep.df["t_s"].to_numpy(dtype=float),
                          clf.predict_proba(prep.df[cols].to_numpy(dtype=np.float32)), prep.y, start, end, vis,
                          f["targets"][0] if f else None, prep.df[cols].to_numpy(dtype=np.float32) if keep_x else None, prep.how))
    return out


def best_live(model, proba: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Per row the most likely live non-nominal class and its probability (the thresholds are applied afterwards)."""
    cl = model.families[MEDICAL].classes_
    usable = np.asarray([c != "nominal" and model.is_live(c) for c in cl])
    masked = np.where(usable[None, :], proba, -1.0)
    best = masked.argmax(axis=1)
    return cl[best], masked[np.arange(len(masked)), best]


def episodes(over: np.ndarray, t: np.ndarray, confirm_s: float) -> list[tuple[float, float]]:
    """(start, confirmation) of every stretch of ``over`` lasting ``confirm_s``."""
    out, start, done = [], None, False
    for i, flag in enumerate(over):
        if not flag:
            start, done = None, False
            continue
        start = i if start is None else start
        if not done and t[i] - t[start] >= confirm_s:
            out.append((float(t[start]), float(t[i])))
            done = True
    return out


def nominal_slices(val: list[ValRun]) -> list[tuple[ValRun, slice]]:
    """The nominal days of validation: all of an N1 run, the rows of an M run before its event starts."""
    out = []
    for v in val:
        n = len(v.t) if v.start_s is None else int(np.searchsorted(v.t, v.start_s, side="left"))
        if n > 0:
            out.append((v, slice(0, n)))
    return out


def tune(model, val: list[ValRun], confirm: dict[str, float], fa_target: float, log=print) -> dict:
    """Per class the lowest threshold with at most ``fa_target`` false alarms per day on the nominal validation days; the recall at it."""
    cl = [c for c in model.families[MEDICAL].classes_ if c != "nominal" and model.is_live(c)]
    nom = nominal_slices(val)
    days = sum((v.t[s][-1] - v.t[s][0]) / 86400.0 for v, s in nom if len(v.t[s]) > 1)
    best = {id(v): best_live(model, v.proba) for v in val}
    table: dict[str, list[dict]] = {}
    chosen: dict[str, float] = {}
    for label in cl:
        rows = []
        for thr in THRESHOLDS:
            n_fa = 0
            for v, s in nom:
                lab, p = best[id(v)]
                n_fa += len(episodes((lab[s] == label) & (p[s] >= thr), v.t[s], confirm.get(label, 300.0)))
            ev = [v for v in val if v.event == label]
            det = 0
            for v in ev:
                lab, p = best[id(v)]
                hits = [e for e in episodes((lab == label) & (p >= thr), v.t, confirm.get(label, 300.0))
                        if v.start_s <= e[1] <= v.end_s + AFTER_END_S]
                det += bool(hits)
            rows.append({"threshold": thr, "false_alarms": n_fa, "per_day": n_fa / days if days else float("nan"),
                         "detected": det, "events": len(ev)})
        table[label] = rows
        ok = [r for r in rows if r["per_day"] <= fa_target]
        chosen[label] = ok[0]["threshold"] if ok else THRESHOLDS[-1]
        pick = next(r for r in rows if r["threshold"] == chosen[label])
        log(f"{label:32s} min_proba {chosen[label]:.2f}  FA {pick['per_day']:.3f}/day ({pick['false_alarms']} in {days:.1f} d)  "
            f"recall {pick['detected']}/{pick['events']}" + ("" if ok else "   (target not reached at the highest threshold)"))
    return {"nominal_days": days, "table": table, "chosen": chosen}


def confusion(model, val: list[ValRun], labels: list[str]) -> pd.DataFrame:
    """Row-level confusion on the validation event rows (truth = the class from the visible time; prediction = the decision of the live
    detector with the tuned thresholds, ``nominal`` when none)."""
    cols = [*labels, "nominal"]
    m = pd.DataFrame(0, index=labels, columns=cols)
    for v in val:
        if v.event is None:
            continue
        lab, p = best_live(model, v.proba)
        thr = np.asarray([model.threshold(c, 0.6) for c in lab])
        pred = np.where(p >= thr, lab, "nominal")
        sel = v.y == v.event
        for got, n in zip(*np.unique(pred[sel], return_counts=True), strict=True):
            m.loc[v.event, got if got in cols else "nominal"] += int(n)
    return m


def event_table(model, val: list[ValRun], confirm: dict[str, float]) -> dict:
    """Event-level on the validation runs with the tuned thresholds: detected with the right label, with another label, missed."""
    res: dict[str, dict] = {}
    for v in val:
        if v.event is None:
            continue
        lab, p = best_live(model, v.proba)
        thr = np.asarray([model.threshold(c, 0.6) for c in lab])
        dec = np.where(p >= thr, lab, "nominal")
        right = [e for e in episodes(dec == v.event, v.t, confirm.get(v.event, 300.0)) if v.start_s <= e[1] <= v.end_s + AFTER_END_S]
        other = any(episodes(dec == c, v.t, confirm.get(c, 300.0)) and any(v.start_s <= e[1] <= v.end_s + AFTER_END_S
                                                                         for e in episodes(dec == c, v.t, confirm.get(c, 300.0)))
                    for c in set(dec) - {"nominal", v.event})
        r = res.setdefault(v.event, {"events": 0, "right_label": 0, "other_label_only": 0, "missed": 0, "delays_s": []})
        r["events"] += 1
        if right:
            r["right_label"] += 1
            r["delays_s"].append(max(0.0, right[0][1] - (v.visible_s if v.visible_s is not None else v.start_s)))
        elif other:
            r["other_label_only"] += 1
        else:
            r["missed"] += 1
    return res


def write_json(path: Path, payload: dict) -> None:
    path.write_text(json.dumps(payload, indent=1, default=float), encoding="utf-8")


def stamp() -> str:
    return datetime.datetime.now().isoformat(timespec="seconds")


# ------------------------------------------------------------------ the training
def train(args) -> int:
    import joblib
    import yaml
    from sklearn.ensemble import HistGradientBoostingClassifier

    classes = yaml.safe_load(Path(args.classes).read_text(encoding="utf-8"))
    base = joblib.load(args.base_model)  # our own file: joblib runs code on load
    cols, scale, mean = list(base.columns), np.asarray(base.scale), np.asarray(base.mean)
    train_seeds, val_seeds = set(parse_seeds(args.train_seeds)), set(parse_seeds(args.val_seeds))
    runs = load_all([Path(d) for d in args.features] if args.features else None)
    twins = twin_index(runs)
    print(f"{len(runs)} runs read, {sum(len(v) for v in twins.values())} possible twins", flush=True)

    # ---- training rows
    frames, counts = [], {}
    skipped = []
    for r in runs:
        if not is_training_run(r, train_seeds):
            continue
        prep = prepare(r, twins, scale, cols, classes, args.visible_k, args.fallback_visible)
        if prep is None:
            skipped.append(r.name)
            continue
        sel = keep_rows(prep.y, args.stride)
        d = prep.df.loc[sel, cols].astype(np.float32)
        d["y"] = prep.y[sel]
        frames.append(d)
        counts[prep.how] = counts.get(prep.how, 0) + 1
        del prep
    if skipped:
        print(f"no twin for {len(skipped)} training runs (e.g. {skipped[0]}): skipped; wait for the twins or pass --fallback-visible", flush=True)
    if not frames:
        raise SystemExit("no training rows")
    train_df = pd.concat(frames, ignore_index=True)
    y = train_df.pop("y").to_numpy()
    X = train_df[cols].to_numpy(dtype=np.float32)
    n_pos = pd.Series(y[y != "nominal"]).value_counts().to_dict()
    print(f"training rows {len(y)}: nominal {(y == 'nominal').sum()}, positives {n_pos}; visible time from: {counts}", flush=True)
    clf = HistGradientBoostingClassifier(max_iter=args.max_iter, learning_rate=0.1, class_weight="balanced", random_state=0).fit(X, y)

    # ---- the model: the other families from the base, the medical one new
    labels = sorted(c for c, v in classes.items() if v["family"] == MEDICAL)
    families = {**{f: c for f, c in base.families.items() if f != MEDICAL}, MEDICAL: clf}
    def signature(lab: str) -> np.ndarray:  # the mean z-score of the rows of a class, with the scale of the base model
        zl = (X[y == lab] - mean) / scale
        return np.where(np.isfinite(zl), zl, 0.0).mean(axis=0)

    signatures = {**{k: v for k, v in base.signatures.items() if classes.get(k, {}).get("family") != MEDICAL},
                  **{lab: signature(lab) for lab in n_pos}}
    live = {lab: bool(n_pos.get(lab, 0) >= args.min_rows) for lab in labels}
    from ares3.plugins.monitor.ml.diagnoser import DiagnoserModel

    model = DiagnoserModel(
        keys=base.keys, columns=cols, clock_periods_s=base.clock_periods_s, mean=mean, scale=scale, families=families,
        signatures=signatures, sensor_info=base.sensor_info, phrases={**base.phrases, **{k: v["phrase"] for k, v in classes.items()}},
        live={**getattr(base, "live", {}), **live}, min_proba=dict(getattr(base, "min_proba", {})),
        info={**base.info, "medical": {"train_seeds": sorted(train_seeds), "stride": args.stride, "visible_k": args.visible_k,
                                       "positive_rows": n_pos, "live": live, "min_rows": args.min_rows, "visible_from": counts,
                                       "twin_identity": identity_summary(),
                                       "fallback_visible_labels": sorted(FALLBACK_LABELS), "base_model": str(args.base_model), **provenance()}})
    for lab, ok in live.items():
        if not ok:
            print(f"{lab}: {n_pos.get(lab, 0)} positive rows (< {args.min_rows}): trained but NOT live", flush=True)

    # ---- validation: thresholds, confusion, events
    confirm = {k: v.get("confirm_s", 300.0) for k, v in classes.items()}
    val_runs = [r for r in runs if r.seed in val_seeds and (r.group == "N1" or r.group.startswith("M"))]
    val = predict_val(clf, val_runs, twins, scale, cols, classes, args.visible_k, args.fallback_visible)
    tuned = tune(model, val, confirm, args.fa_target)
    model.min_proba.update(tuned["chosen"])
    live_labels = [lab for lab in labels if model.is_live(lab)]
    conf = confusion(model, val, live_labels)
    events = event_table(model, val, confirm)
    print("\nconfusion on the validation event rows (rows = truth):")
    print(conf.to_string(), flush=True)
    print("\nevents on validation:", {k: {kk: vv for kk, vv in v.items() if kk != "delays_s"} for k, v in events.items()}, flush=True)
    model.info["medical"]["validation"] = {"seeds": sorted(val_seeds), "nominal_days": tuned["nominal_days"], "fa_target_per_day": args.fa_target,
                                           "thresholds": tuned["chosen"], "test_seeds_read": False}
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    joblib.dump(model, out / "diagnoser.joblib")
    card_path = out / "model_card_diagnoser.json"
    write_json(card_path, {"trained_at": stamp(), "families": {"medical": "new"}, "other_families_from": str(args.base_model),
                           "info": model.info, "tuning": {k: v for k, v in tuned.items()}, "confusion_val": json.loads(conf.to_json(orient="split")),
                           "events_val": events, "skipped_without_twin": skipped})
    print(f"\nwritten {out / 'diagnoser.joblib'} and {card_path}", flush=True)
    return 0


def _cols(df: pd.DataFrame) -> list[str]:
    return feature_columns(df)
