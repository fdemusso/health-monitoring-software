# ---- crew and monitor, derived from the shared files so Luca's schedules and the playbooks stay the single source ----------
SLEEP_QUARTERS = {"cmd": "CQ1", "bot": "CQ2", "eng": "CQ3", "med": "CQ4"}  # med sleeps in CQ4: the cabin of F-ATT-CQFAN-FOD
HAB_MAP = {"meal": "NOD1", "work": "NOD1", "rest": "NOD2", "exercise_aerobic": "NOD3", "exercise_resistive": "NOD3",
           "recovery": "NOD3", "exercise": "NOD3"}
OTHER_MAP = {"lab": "USL", "airlock": "AL", "greenhouse": "COL"}  # the mini habitat's modules -> the ISS ones; ``eva`` stays


EXERCISE_MAP = {"cmd": "NOD3", "bot": "NOD3", "eng": "USL", "med": "USL"}  # T2 / ARED in Tranquility, CEVIS in Destiny: not all four on one treadmill


def build_crew() -> str:
    crew = yaml.safe_load((ROOT / "scenarios" / "crew.yaml").read_text(encoding="utf-8"))
    for m in crew["members"]:
        for b in m["schedule"]:
            mod = b["module"]
            if mod == "hab":
                if b["activity"] in ("exercise_aerobic", "exercise_resistive", "exercise", "recovery"):
                    b["module"] = EXERCISE_MAP[m["id"]]
                else:
                    b["module"] = SLEEP_QUARTERS[m["id"]] if b["activity"] == "sleep" else (
                        "USL" if m["id"] == "cmd" and b["activity"] == "work" else HAB_MAP.get(b["activity"], "NOD1"))
            else:
                b["module"] = OTHER_MAP.get(mod, mod)
    c = ("# Crew of the ISS station: Luca's profiles and schedules (scenarios/crew.yaml, PLACEHOLDER - awaiting review by Luca) with the\n"
         "# places moved onto the station: sleep in the crew quarters, meals in Unity, work in Destiny / Columbus, exercise in Tranquility,\n"
         "# EVA through Quest. Which module each person works in is OUR proposal.\n")
    return HEADER + c + yaml.safe_dump(crew, sort_keys=False, width=140, allow_unicode=True)


def build_monitor() -> str:
    text = (ROOT / "scenarios" / "monitor_placeholder.yaml").read_text(encoding="utf-8")
    pressure_targets = ["NOD1", "USL", "NOD2", "NOD3", "COL", "JPM", "CUP", "AL", "SM", "PRK", "lifeboat"]
    swaps = [
        ("targets: [hab, lab, greenhouse, airlock, lifeboat]", f"targets: [{', '.join(pressure_targets)}]"),
        ('target: "hab:{module}", command: close', 'target: "isolate:{module}", command: close'),
        ('target: "press_{module}"', 'target: PCA'),
        ('target: "o2gen_{module}"', 'target: OGA'),
        ('{do: actuator, target: "scrubber_{module}", command: "on", level: auto, reason: maximise CO2 removal}',
         '{do: actuator, target: CDRA-B, command: "on", level: auto, reason: wake the standby scrubber}'),
        ("    metric: ppCO2\n    params: {max: 3.0, window_s: 3600}",
         f"    metric: ppCO2\n    targets: [{', '.join(pressure_targets)}]   # not the cabins: no station alarm for them (alarm_mode never)\n"
         "    params: {max: 3.0, window_s: 3600}"),
        ("# PLACEHOLDER - awaiting the team (and Mario for the final sensor set).", "# Monitoring of the ISS station (derived from monitor_placeholder.yaml by tools/build_station.py)."),
    ]
    for a, b in swaps:
        assert a in text, a
        text = text.replace(a, b)
    return HEADER + "# On the station a module is isolated by closing ALL its hatches (`isolate:<module>`), never the vehicle's; gas introduction is the PCA / OGA.\n" + text


def outputs(wb) -> dict[Path, str]:
    files: dict[Path, str] = {OUT / "modules.yaml": build_modules(wb)}
    sensors, groups = build_sensors(wb)
    files[OUT / "sensors.yaml"] = sensors
    files[OUT / "sensor_groups.csv"] = groups
    files[OUT / "actuators.yaml"] = build_actuators(wb)
    files[OUT / "crew.yaml"] = build_crew()
    files[OUT / "monitor.yaml"] = build_monitor()
    for fid, spec in fault_table().items():
        files[OUT / "faults" / f"{fid}.yaml"] = HEADER + yaml.safe_dump({"faults": spec["faults"]}, sort_keys=False)
        files[OUT / "events" / f"{fid}.yaml"] = HEADER + yaml.safe_dump(event_scenario(fid, spec), sort_keys=False)
    return files


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    files = outputs(load())
    stale = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        print("up to date" if not stale else "stale: " + ", ".join(str(p.relative_to(ROOT)) for p in stale))
        return 1 if stale else 0
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(files)} files under {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
