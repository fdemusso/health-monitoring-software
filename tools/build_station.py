"""Turns Mario's workbook (notebooks/mario/ARES3_Stazione_Sensori.xlsx) into the official station YAML.

    uv run --with openpyxl python tools/build_station.py            # writes scenarios/station/{modules,sensors,actuators}.yaml, faults, events
    uv run --with openpyxl python tools/build_station.py --check     # exit 1 when the committed files differ from the workbook

The workbook is the source of truth for every number it contains (layout, hatches, sensors, actuators, telemetry); this
script only translates rows into our parameters. What the workbook does not say is written HERE, each marked ESTIMATE:
rack heat loads, the technology tables (bias of a unit, calibration interval), the mapping of its 26 faults onto our fault
types, and the compression of month-long processes to simulated days (``TIME_COMPRESSION``).
"""

