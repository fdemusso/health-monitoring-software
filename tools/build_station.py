# ---- what the workbook does not give: ESTIMATES ------------------------------------------------------------------------
RACK_HEAT_W = {  # equipment heat into the cabin air, always on. Sized so each CCAA (2.5 kW) holds its module in band.
    "NOD1": 400, "USL": 1500, "NOD2": 400, "NOD3": 1000, "COL": 1000, "JPM": 1300, "CUP": 80, "AL": 100,
    "SM": 300, "PRK": 0, "CQ1": 60, "CQ2": 60, "CQ3": 60, "CQ4": 60,
}
UA_W_M2_K = 0.04  # heat leak through the insulation per m2 of skin. ESTIMATE
SURFACE_K = 4.6  # skin area = 4.6 V^(2/3): a cylinder, 120 m2 for the 106 m3 Lab (Mario's figure)
BIAS_SIGMA = {  # fixed error of one unit, 1 sigma, in the unit of the reading. ESTIMATE from the datasheet accuracy class
    "T": 0.10, "RH": 1.0, "P": 0.05, "ppO2_galv": 0.10, "ppO2_para": 0.05, "ppCO2": 0.015,
}
CALIBRATION_D = {"ppO2_galv": 30.0, "mca": 42.0}  # galvanic cell recalibrated monthly [F19]; MCA every 6 weeks [F21]
TIME_COMPRESSION = 30.0  # a drift quoted per MONTH runs per DAY in the fault scenarios (a 3-day run shows a month)
DAY = 86400.0
CROSS_NDIR = {"pressure_pct_per_hpa": 0.15, "oxygen_pct_per_pct": -0.08, "temperature_pct_per_c": 0.05}  # [F20]
HEADER = "# GENERATED by tools/build_station.py from notebooks/mario/ARES3_Stazione_Sensori.xlsx - edit the tool, not this file.\n"


def load() -> openpyxl.Workbook:
    return openpyxl.load_workbook(XLSX, data_only=True)


def table(wb, sheet: str, first_col: str = "id") -> list[dict]:
    ws = wb[sheet]
    it = ws.iter_rows(values_only=True)
    hdr = [re.sub(r"\s+", " ", str(h)).strip() if h else "" for h in next(it)]
    rows = []
    for r in it:
        if r[0] is None or not r[3 if sheet != "03_SENSORI" else 1]:
            continue
        rows.append({h: v for h, v in zip(hdr, r, strict=False) if h})
    return rows


def num(v, default=0.0) -> float:
    return default if v is None or v == "" else float(v)


def dump(path: Path, data: dict, comment: str) -> str:
    return HEADER + comment + yaml.safe_dump(data, sort_keys=False, width=140, allow_unicode=True)


# ---- layout ------------------------------------------------------------------------------------------------------------
def build_modules(wb) -> str:
    mods = []
    for r in table(wb, "01_MODULI"):
        if r["id"] in ("", None) or not isinstance(r.get("V pressurizzato [m3]"), (int, float)):
            continue
        v_p = num(r["V pressurizzato [m3]"])
        v_free = num(r["V aria libera [m3] (calc)"])
        surface = SURFACE_K * v_p ** (2.0 / 3.0)
        mods.append({"id": r["id"], "volume_m3": round(v_free, 4), "thermal_mass_j_k": round(num(r["Capacita' termica [J/K] (calc)"])),
                     "ua_w_k": round(UA_W_M2_K * surface, 2), "surface_m2": round(surface, 1),
                     "base_heat_w": RACK_HEAT_W[r["id"]],
                     "leak_kg_day": round(num(r["Perdita nominale [kg/giorno] (calc)"]), 6),
                     # the catalog: a fouled cabin fan raises NO station alarm
                     **({"alarm_mode": "never"} if r["id"].startswith("CQ") else {})})
    hatches = []
    for r in table(wb, "02_PORTELLI"):
        if not str(r["id"]).startswith(("H-", "V-")):
            continue
        closable = str(r["Comandabile / chiudibile"]).strip().lower() == "si"
        imv = r["IMV associato"] if r["IMV associato"] not in (None, "nessuno") else None
        h = {"id": r["id"], "a": r["Da"], "b": r["A"], "diffusion_coeff": num(r["G gas passivo [m3/s]"]),
             "gp_open": num(r["G pressione aperto [mol/(s*kPa)]"]), "gp_closed": num(r["G pressione chiuso [mol/(s*kPa)]"]),
             "conduction_w_k": num(r["G termica chiuso [W/K]"])}
        if imv:
            h["imv"] = imv
        if not closable:
            h["closable"] = False
            # ESTIMATE: only ~7 % of a cabin fan's CO2 flow washes the face in microgravity (no convection). A well-mixed cabin
            # would sit 0.07 mmHg above the node whatever the fan does and the catalog's signature (F-ATT-CQFAN-FOD) could not
            # exist. Measured with 0.07: a healthy cabin peaks ~3.2 mmHg at night, one with its fan at 20 CFM ~4.4 (the catalog quotes 5-7: not reached).
            # The cabins are not alarmed (alarm_mode never): the catalog says no station alarm fires for this fault
            h["mixing_efficiency"] = 0.07
        hatches.append(h)
    c = ("# Station layout: the 14 volumes and 13 connections of sheets 01_MODULI and 02_PORTELLI.\n"
         "# volume_m3 is the FREE air volume (rack volume excluded). base_heat_w and the heat leak through the insulation (ua_w_k) are ESTIMATES.\n"
         "# The crew-quarters vents (V-*) are ventilated openings, not hatches: never closable. Hatches reference their IMV fan by id.\n")
    return dump(None, {"modules": mods, "hatches": hatches}, c)


# ---- sensors -----------------------------------------------------------------------------------------------------------
def _tech(r) -> str:
    t = str(r["Tecnologia"])
    if t.startswith("Termistore"):
        return "T"
    if t.startswith("Capacitivo"):
        return "RH"
    if t.startswith("Trasduttore"):
        return "P"
    if t.startswith("Cella"):
        return "ppO2_galv"
    if t.startswith("Paramagnetico"):
        return "ppO2_para"
    if t.startswith("NDIR"):
        return "ppCO2"
    if t.startswith("Spettrometro"):
        return "mca"
    raise ValueError(t)


def _drift(r) -> dict:
    d, unit = num(r["Deriva"]), str(r["Unita' deriva"])
    if "lettura/mese" in unit:
        return {"drift_rel_per_year": d / 100.0 * 12.0}
    if "lettura/anno" in unit:
        return {"drift_rel_per_year": d / 100.0}
    if "calibrazioni" in unit:  # 1 % between two calibrations
        return {"drift_rel_per_year": d / 100.0 / (CALIBRATION_D["mca"] / 365.0)}
    return {"drift_abs_per_year": d}


def build_sensors(wb) -> tuple[str, str]:
    out, groups = [], ["id,module,metric,technology,redundancy_group"]
    for r in table(wb, "03_SENSORI"):
        if not r.get("Tecnologia"):
            continue  # the explanatory notes under the table
        tech = _tech(r)
        sid, metric = r["id"], r["Grandezza"]
        p = {"sigma": num(r["Rumore sigma"]), "tau_s": num(r["tau [s]"]), "resolution": num(r["Risoluzione"]),
             "range_min": num(r["Range min"]), "range_max": num(r["Range max"]), **_drift(r),
             "warmup_s": num(r["Warm-up [s]"])}
        if tech == "mca":
            mods = [m.strip() for m in str(r["Posizione"]).split(":")[1].split(",")]
            p.pop("tau_s")
            p.update(modules=mods, cycle_s=1200.0, delay_s=45.0, offset_s=600.0 if str(r["id"]).startswith("mcaB") else 0.0,
                     bias_sigma=round(0.3 * p["sigma"], 6), calibration_interval_d=CALIBRATION_D["mca"])
            kind, rate = "ares3.plugins.sensors.instruments:McaSensor", 1.0  # one row per sample (the rotation sets the rate)
        else:
            p["bias_sigma"] = BIAS_SIGMA[tech]
            if tech == "ppO2_galv":
                p["calibration_interval_d"] = CALIBRATION_D["ppO2_galv"]
            if tech == "ppCO2":
                p["cross"] = CROSS_NDIR
                p["extend_factor"] = 3.0  # the NDIR keeps reading, with growing error, up to 22.8 mmHg [F20]
            if str(r["Satura"]).lower() != "si":
                p["extend_factor"] = 1.0
            kind, rate = "ares3.plugins.sensors.instruments:Instrument", num(r["f campion. [Hz]"], 1.0)
        out.append({"id": sid, "kind": kind, "target": f"module:{r['Modulo']}", "metric": metric, "rate_hz": rate,
                    "params": {k: (round(v, 8) if isinstance(v, float) else v) for k, v in p.items()}})
        groups.append(",".join([sid, r["Modulo"], metric, tech, str(r["Gruppo di ridondanza"] or "")]))
    # actuator telemetry (sheet 05) and the electrical bus
    for r in table_tele(wb):
        out.append(r)
    c = ("# Sensors of sheet 03_SENSORI (62 environmental + 8 MCA channels) and the 26 telemetry channels of sheet 05_TELEMETRIA_ATT.\n"
         "# Redundancy groups are in sensor_groups.csv (metadata for the ML). The MCA rotates over 8 modules: one row per sample.\n"
         "# bias_sigma (the fixed error of one unit), calibration_interval_d and the NDIR range extension are ESTIMATES.\n")
    return dump(None, {"sensors": out}, c), "\n".join(groups) + "\n"


