START = 6 * 3600.0  # a fault starts 6 h into the run: a quiet baseline first


def _f(fid, type_, targets, label, priority, params=None, start=START, duration=None):
    d = {"id": fid, "type": type_, "targets": targets, "start_s": start, "anomaly_type": label, "priority": priority}
    if duration:
        d["duration_s"] = duration
    if params:
        d["params"] = params
    return d


