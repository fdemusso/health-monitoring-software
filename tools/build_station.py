def table_tele(wb) -> list[dict]:
    ws = wb["05_TELEMETRIA_ATT"]
    it = ws.iter_rows(values_only=True)
    hdr = [re.sub(r"\s+", " ", str(h)).strip() if h else "" for h in next(it)]
    out = []
    for raw in it:
        r = dict(zip(hdr, raw, strict=False))
        sid = r.get("id")
        if sid not in TELEMETRY_MAP:
            continue
        target, ch = TELEMETRY_MAP[sid]
        p = {"sigma": num(r["Rumore sigma"]), "tau_s": max(num(r["tau [s]"]), 0.1), "resolution": num(r["Risoluzione"]),
             "range_min": num(r["Range min"]), "range_max": num(r["Range max"])}
        if target.startswith("actuator:"):
            kind, p["channel"] = "ares3.plugins.sensors.instruments:ActuatorTelemetry", ch
            if sid == "imv_usl_fwd_Q":
                p["resolution"] = 1.0
        else:
            kind = "ares3.plugins.sensors.instruments:StationTelemetry"
        out.append({"id": sid, "kind": kind, "target": target, "metric": ch if target.startswith("station") else str(r["Grandezza"]),
                    "rate_hz": num(r["f campion. [Hz]"], 1.0), "params": p})
    return out


# ---- actuators ---------------------------------------------------------------------------------------------------------
def build_actuators(wb) -> str:
    out = []
    for r in table(wb, "04_ATTUATORI"):
        aid, mod = r["id"], r["Modulo"]
        cap = num(r["Capacita'"])
        base = {"id": aid, "module": "NOD3" if mod == "globale" else mod}
        if aid.startswith("CDRA"):
            # eta 0.85: ESTIMATE retuned from Mario's 0.80, so that a nominal day with the exercise sessions of our crew stays
            # under the 3 mmHg (1 h mean) requirement; a 60 % scrubber still settles above it (4.4 mmHg)
            kind, p = "cdra", {"sensor": r["Sensore di comando"], "r0_mol_s": round(num(r["Capacita' SI (calc)"]), 8), "eta": 0.85,
                               "standby": aid == "CDRA-B", "power_w": num(r["Potenza [W]"]), "heat_w": num(r["Calore in cabina [W]"])}
        elif aid == "OGA":
            kind, p = "oga", {"sensor": r["Sensore di comando"], "on_kpa": num(r["Soglia ON"]), "off_kpa": num(r["Soglia OFF"]),
                              "rate_mol_s": round(num(r["Capacita' SI (calc)"]), 8), "start_delay_s": num(r["Ritardo avvio [s]"]),
                              "power_w": num(r["Potenza [W]"]), "standby_w": num(r["Potenza standby [W]"]),
                              "heat_w": num(r["Calore in cabina [W]"])}
        elif aid.startswith("CCAA"):
            kind, p = "ccaa", {"sensor": r["Sensore di comando"], "q_max_w": cap, "power_w": num(r["Potenza [W]"]),
                               "fan_power_w": num(r["Calore in cabina [W]"])}
        elif aid == "PCA":
            kind, p = "pca", {"sensor": r["Sensore di comando"], "on_kpa": 97.9, "off_kpa": 99.5, "relief_kpa": 102.7,
                              "makeup_mol_s": 1.0e-2}
        elif aid.startswith("IMV"):
            kind, p = "fan", {"nominal_cfm": cap}
        elif aid.startswith("FAN-CQ"):
            kind, p = "fan", {"nominal_cfm": cap, "rpm": 3400.0, "current_a": 0.3, "power_w": 15.0}  # speeds, current: ESTIMATE
        elif aid == "TCS":
            kind, p = "tcs", {"capacity_w": cap}
        else:
            raise ValueError(aid)
        out.append({**base, "kind": f"ares3.plugins.actuators.eclss:{ {'cdra':'Cdra','oga':'Oga','ccaa':'Ccaa','pca':'Pca','fan':'Fan','tcs':'Tcs'}[kind] }",
                    "params": p})
    c = ("# The 23 actuators of sheet 04_ATTUATORI. Nominal configuration: ONE CDRA active (CDRA-B in standby), as on the ISS and as\n"
         "# Mario recommends: with two scrubbers no single fault would show. The equipment playbook wakes CDRA-B.\n")
    return dump(None, {"actuators": out}, c)


